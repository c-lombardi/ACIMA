#!/usr/bin/env python3
"""The swap drill: prove an integration seam is real by removing the adapter.

    python3 conformance/swap_drill.py --project conformance/fixtures/third-party/python

The drill copies the project to a disposable directory, deletes every directory owned by a declared
adapter unit, writes a vendor-free stub that implements the port, and then resolves every import of
every application unit (`implementation`, `contracts`, `port`) against the remaining tree and the
language core.

It fails when:

- an application file does not parse;
- an application file imports a declared vendor, a removed adapter, or a package that no longer
  resolves (a vendor that leaked is exactly an import nobody can resolve any more);
- no application file references the port at all — that is an unused declaration, not a seam.

Exit codes: 0 the seam holds, 1 the seam leaked or the drill could not run, 2 bad arguments.
"""
from __future__ import annotations

import argparse
import ast
import json
import shutil
import sys
import tempfile
from pathlib import Path

APPLICATION_ROLES = ("implementation", "contracts", "port")
STUB = '''"""Generated by conformance/swap_drill.py: a vendor-free port implementation."""


class StubAdapter:
    """Stand-in that proves the application compiles with the vendor removed."""

    def open(self, note):
        """Accept a note and do nothing."""
        return None

    def read(self):
        """Return no text."""
        return ""
'''


def fail(message: str) -> int:
    print(f"fail  {message}", file=sys.stderr)
    return 1


def unit_paths(config: dict) -> dict[str, dict]:
    return {unit["id"]: unit for unit in config.get("units", [])}


def under(path: str, roots: list[str]) -> str | None:
    for root in roots:
        prefix = root.rstrip("/")
        if path == prefix or path.startswith(prefix + "/"):
            return prefix
    return None


def resolve(module: str, level: int, current: str, root: Path) -> str | None:
    if level:
        base = current.split("/")[:-1]
        if level > 1:
            base = base[: -(level - 1)]
        parts = base + [part for part in module.split(".") if part]
    else:
        parts = [part for part in module.split(".") if part]
    for prefix in ("", "src"):
        candidate = "/".join(([prefix] if prefix else []) + parts)
        for suffix in (".py", "/__init__.py"):
            if (root / f"{candidate}{suffix}").is_file():
                return f"{candidate}{suffix}"
    return None


def imports_of(tree: ast.Module) -> list[tuple[str, int, int]]:
    out: list[tuple[str, int, int]] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                out.append((alias.name, 0, node.lineno))
        elif isinstance(node, ast.ImportFrom):
            out.append((node.module or "", node.level, node.lineno))
    return out


def drill(project: Path, config_name: str) -> int:
    config_path = project / config_name
    if not config_path.is_file():
        return fail(f"no {config_name} at {project}")
    config = json.loads(config_path.read_text(encoding="utf-8"))
    units = unit_paths(config)
    externals = config.get("externals") if isinstance(config.get("externals"), dict) else {}
    adapters = {str(entry.get("adapter", "")) for entry in externals.values()
                if isinstance(entry, dict) and entry.get("tier") == "integration"}
    adapters.discard("")
    if not adapters:
        return fail("no integration adapter declared; the drill has nothing to remove")
    adapter_roots: list[str] = []
    for unit_id in sorted(adapters):
        unit = units.get(unit_id)
        if unit is None:
            return fail(f"externals names adapter {unit_id}, which is not a declared unit")
        adapter_roots.extend(unit.get("paths", []))
    vendor_specifiers = set()
    for name, entry in externals.items():
        if isinstance(entry, dict) and entry.get("tier") == "integration":
            vendor_specifiers.add(name)
            vendor_specifiers.update(str(value) for value in entry.get("specifiers", []))

    application = [unit for unit in config.get("units", []) if unit.get("role") in APPLICATION_ROLES]
    port_roots = [path for unit in config.get("units", []) if unit.get("role") == "port"
                  for path in unit.get("paths", [])]

    with tempfile.TemporaryDirectory(prefix="acima-swap-") as temporary:
        root = Path(temporary) / "project"
        shutil.copytree(project, root)
        removed = []
        for relative in adapter_roots:
            target = root / relative
            if target.exists():
                shutil.rmtree(target)
                removed.append(relative)
        if not removed:
            return fail("no adapter directory existed to remove; the declaration is stale")
        (root / "src").mkdir(parents=True, exist_ok=True)
        (root / "src" / "stub_adapter.py").write_text(STUB, encoding="utf-8")

        problems: list[str] = []
        port_references = 0
        checked = 0
        for unit in application:
            for relative in unit.get("paths", []):
                for path in sorted(root.rglob(f"{relative.removeprefix('./')}/**/*.py")):
                    rel = path.relative_to(root).as_posix()
                    checked += 1
                    try:
                        tree = ast.parse(path.read_text(encoding="utf-8"))
                    except SyntaxError as error:
                        problems.append(f"{rel}: does not parse ({error.msg})")
                        continue
                    for module, level, line in imports_of(tree):
                        top = module.split(".")[0]
                        if level == 0 and (module in vendor_specifiers or top in vendor_specifiers):
                            problems.append(f"{rel}:{line}: imports the vendor {module}")
                            continue
                        target = resolve(module, level, rel, root)
                        if target is None:
                            if level == 0 and top and top in sys.stdlib_module_names:
                                continue
                            problems.append(f"{rel}:{line}: cannot resolve {module} without the adapter")
                            continue
                        if under(target, removed):
                            problems.append(f"{rel}:{line}: still reaches the removed adapter {target}")
                        if under(target, port_roots):
                            port_references += 1
        if checked == 0:
            return fail("no application source files were found; a drill over nothing proves nothing")
        if port_references == 0:
            problems.append("no application file references the port; the seam is declared, not used")
        if problems:
            for problem in problems:
                print(f"  {problem}", file=sys.stderr)
            return fail(f"{len(problems)} problem(s): the application does not survive the swap")
        print(f"ok    swap drill: {checked} application file(s) compile against the port with "
              f"{', '.join(removed)} removed")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="prove an integration seam by removing the adapter")
    parser.add_argument("--project", required=True, help="fixture directory to drill")
    parser.add_argument("--config", default="acima.config.json")
    args = parser.parse_args()
    project = Path(args.project).resolve()
    if not project.is_dir():
        print(f"acima: no project at {project}", file=sys.stderr)
        return 2
    if not args.config.endswith(".json"):
        print("acima: the swap drill is implemented for Python fixtures only", file=sys.stderr)
        return 2
    return drill(project, args.config)


if __name__ == "__main__":
    raise SystemExit(main())
